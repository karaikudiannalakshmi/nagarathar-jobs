// Helper to get a translation
export function getT(lang) {
  return function t(section, key) {
    try {
      const val = translations[section][key]
      if (!val) return `[${section}.${key}]`
      return val[lang] || val['en']
    } catch {
      return `[${section}.${key}]`
    }
  }
}
